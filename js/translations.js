function setLanguage(lang) {
  if (!translations[lang]) lang = 'en';
  localStorage.setItem('cpye_lang', lang);

  const t = translations[lang];
  
  // Update elements with data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (t[key]) {
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = t[key];
      } else {
        el.innerHTML = t[key];
      }
    }
  });

  // Update active status in selector
  document.querySelectorAll('.lang-option').forEach(btn => {
    btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
  });

  const currentLangLabel = document.querySelector('.current-lang-label');
  if (currentLangLabel) {
    const labels = { en: 'English', ta: 'தமிழ்', si: 'සිංහල' };
    currentLangLabel.textContent = labels[lang] || 'English';
  }

  // Adjust document lang attribute
  document.documentElement.lang = lang;
}

document.addEventListener('DOMContentLoaded', () => {
  const savedLang = localStorage.getItem('cpye_lang') || 'en';
  setLanguage(savedLang);

  // Dropdown toggle logic
  const langDropdownToggle = document.querySelector('.lang-dropdown-toggle');
  const langDropdown = document.querySelector('.lang-dropdown');

  if (langDropdownToggle && langDropdown) {
    langDropdownToggle.addEventListener('click', (e) => {
      e.stopPropagation();
      langDropdown.classList.toggle('active');
    });

    document.addEventListener('click', () => {
      langDropdown.classList.remove('active');
    });
  }

  // Language item click
  document.querySelectorAll('.lang-option').forEach(option => {
    option.addEventListener('click', (e) => {
      e.preventDefault();
      const lang = option.getAttribute('data-lang');
      setLanguage(lang);
      if (langDropdown) langDropdown.classList.remove('active');
    });
  });
});
